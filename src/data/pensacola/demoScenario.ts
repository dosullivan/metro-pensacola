import { DEFAULT_ASSUMPTIONS } from '../assumptions';
import type { Coordinate, Scenario, Station, TransitLine } from '../../types';

interface StationSeed {
  id: string;
  name: string;
  coordinate: Coordinate;
}

function buildStations(lineId: string, stationSeeds: StationSeed[]): Station[] {
  return stationSeeds.map((station, order) => ({
    ...station,
    lineId,
    order
  }));
}

function buildLine(
  id: string,
  name: string,
  headwayMinutes: TransitLine['headwayMinutes'],
  geometry: Coordinate[],
  stationSeeds: StationSeed[]
): TransitLine {
  return {
    id,
    name,
    technology: 'brt',
    color: DEFAULT_ASSUMPTIONS.technologies.brt.color,
    headwayMinutes,
    geometry,
    stations: buildStations(id, stationSeeds)
  };
}

